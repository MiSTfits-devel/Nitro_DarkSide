"""Seeded generator of ARMv4T-specific ARM7 fixtures with independent
expectations.

    hs_arm7_v4t_gen.py SEED OUT.S OUT.expected

Each program (boot ROM at 0) runs 16-24 random cases. Every case reaches a
target code block that sets r5 to a random byte k (or, for BL, computes
values) and returns; the mailbox records the result. The expectation is
this script's own model of the ARMv4T rules, not any core:

  * LDR pc / LDM {pc} in ARM state: the loaded address with bit 0 cleared,
    state kept (ARM); bit 0 of the loaded value is random.
  * Thumb POP {pc}: the popped address with bit 0 cleared, state kept
    (Thumb); bit 0 random.
  * BX Rm: state from bit 0 (ARM or Thumb target), on both architectures
    (control case).
  * Thumb BL pair forward or backward: LR = address after the suffix | 1;
    the subroutine adds 3 and returns with MOV pc, lr (stays Thumb).

On an ARMv5 core a state-keeping load with the "other" bit 0 switches state
and runs the target block as the wrong instruction set, so the mailbox (or
a fault) differs. Mailbox slot k is RAM word k at 0x02000000; at most 48
words.
"""
import random
import sys


def main():
    seed, out_s, out_e = int(sys.argv[1]), sys.argv[2], sys.argv[3]
    rng = random.Random(seed)
    lines = [
        "/* Generated by sim/tests/hs_arm7_v4t_gen.py (seed %d). */" % seed,
        ".syntax unified", ".cpu arm7tdmi", ".arm", ".text",
        ".set slot, 0",
        ".macro put reg", "    str     \\reg, [r11, #slot*4]", "    .set    slot, slot + 1", ".endm",
        "    b       reset",
    ] + ["    b       .            @ vector %#x" % (4 * v) for v in range(1, 8)] + [
        "reset:",
        "    mov     r11, #0x02000000",
        "    msr     cpsr_c, #0xdf",
        "    add     sp, r11, #0x100",
    ]
    expected = []
    for n in range(rng.randint(16, 24)):
        kind = rng.choice(["ldr", "ldm", "pop", "bx_arm", "bx_thumb", "bl"])
        k = rng.randint(1, 255)
        b = rng.randint(0, 1)
        # The first case always separates ARMv4T from ARMv5: an ARM load to
        # PC with bit 0 set, or a Thumb POP {pc} with bit 0 clear.
        if n == 0:
            kind = rng.choice(["ldr", "ldm", "pop"])
            b = 0 if kind == "pop" else 1
        lab = "c%d" % n
        if kind in ("ldr", "ldm"):
            lines += [
                "    adr     r6, %s_ret" % lab,
                "    mov     r5, #0",
            ]
            if kind == "ldr":
                lines += ["    ldr     pc, =%s_t + %d" % (lab, b)]
            else:
                lines += [
                    "    adr     r0, %s_t + %d" % (lab, b),
                    "    stmdb   sp!, {r0}",
                    "    ldmia   sp!, {pc}",
                ]
            lines += [
                "    .word   0xe7f000f0",
                "%s_t:" % lab,
                "    mov     r5, #%d" % k,
                "    mov     pc, r6",
                "%s_ret:" % lab,
                "    put     r5",
            ]
            expected.append((k, "%s: %s pc = target | %d, ARM kept" % (lab, kind.upper(), b)))
        elif kind == "pop":
            lines += [
                "    adr     r6, %s_ret" % lab,
                "    mov     r5, #0",
                "    adr     r0, %s_th + 1" % lab,
                "    bx      r0",
                ".thumb", ".balign 4",
                "%s_th:" % lab,
                "    adr     r0, %s_t" % lab,
            ] + (["    adds    r0, #1"] if b else []) + [
                "    push    {r0}",
                "    pop     {pc}",
                "    .hword  0xde00",
                ".balign 4",
                "%s_t:" % lab,
                "    movs    r5, #%d" % k,
                "    bx      r6",
                ".arm", ".balign 4",
                "%s_ret:" % lab,
                "    put     r5",
            ]
            expected.append((k, "%s: Thumb POP {pc} = target | %d, Thumb kept" % (lab, b)))
        elif kind == "bx_arm":
            lines += [
                "    adr     r6, %s_ret" % lab,
                "    adr     r0, %s_t" % lab,
                "    bx      r0",
                "    .word   0xe7f000f0",
                "%s_t:" % lab,
                "    mov     r5, #%d" % k,
                "    mov     pc, r6",
                "%s_ret:" % lab,
                "    put     r5",
            ]
            expected.append((k, "%s: BX to ARM (control)" % lab))
        elif kind == "bx_thumb":
            lines += [
                "    adr     r6, %s_ret" % lab,
                "    adr     r0, %s_t + 1" % lab,
                "    bx      r0",
                ".thumb", ".balign 4",
                "%s_t:" % lab,
                "    movs    r5, #%d" % k,
                "    bx      r6",
                ".arm", ".balign 4",
                "%s_ret:" % lab,
                "    put     r5",
            ]
            expected.append((k, "%s: BX to Thumb (control)" % lab))
        else:
            back = rng.randint(0, 1)
            pad = rng.randint(0, 6)
            sub = [
                "%s_sub:" % lab,
                "    adds    r1, #3",
                "    mov     r12, lr",
                "    mov     pc, lr",
            ]
            lines += [
                "    adr     r6, %s_ret" % lab,
                "    adr     r0, %s_th + 1" % lab,
                "    bx      r0",
                ".thumb", ".balign 4",
            ]
            if back:
                lines += ["    .hword  0xde00"] + sub + ["    .hword  0x46c0"] * pad
            lines += [
                "%s_th:" % lab,
                "    movs    r1, #%d" % (k & 0x7f),
                "    bl      %s_sub" % lab,
                "%s_next:" % lab,
                "    bx      r6",
            ]
            if not back:
                lines += ["    .hword  0x46c0"] * pad + sub
            lines += [
                ".arm", ".balign 4",
                "%s_ret:" % lab,
                "    put     r1",
                "    adr     r7, %s_next + 1" % lab,
                "    sub     r0, r12, r7",
                "    put     r0",
            ]
            expected.append(((k & 0x7f) + 3, "%s: Thumb BL %s, subroutine added 3" % (lab, "backward" if back else "forward")))
            expected.append((0, "%s: LR in the subroutine - (next | 1)" % lab))
    assert len(expected) <= 48
    lines += ["done:", "    b       done", ".ltorg", ""]
    with open(out_s, "w") as f:
        f.write("\n".join(lines))
    with open(out_e, "w") as f:
        for i, (v, why) in enumerate(expected):
            f.write("%08x  # %d %s\n" % (v, i, why))


if __name__ == "__main__":
    main()
