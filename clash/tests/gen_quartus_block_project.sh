# Write the standalone Quartus project for one generated Clash block, so a new
# block needs no hand-copied qsf: the top entity, the revision and the RTL file
# list are the only inputs.
#
#   clash/tests/gen_quartus_block_project.sh <block> <top-entity> <rtl.v>...
#
# Creates clash/tests/quartus-<block>/NDS_<BLOCK>.{qpf,qsf,sdc}. No pins are
# assigned (every port is virtual): the fit measures utilisation and the
# register-to-register timing of the block itself, at the shipping 3D island clock.
set -eu

block=${1:?usage: gen_quartus_block_project.sh <block> <top-entity> <rtl.v>...}
top=${2:?missing top entity}
shift 2
[ "$#" -ge 1 ] || { echo "no RTL file given" >&2; exit 2; }

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
rev="NDS_$(printf '%s' "$block" | tr '[:lower:]' '[:upper:]')"
dir="$here/quartus-$block"
mkdir -p "$dir"

cat >"$dir/$rev.qpf" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE quartzProject PUBLIC "-//www.altera.com/DTD/quartusProject" "http://www.altera.com/DTD/quartusProject.dtd">
<quartusProject version="1.0">
 <project revision="$rev" name="$rev">
  <platform name="Cyclone V"/>
 </project>
</quartusProject>
EOF

{
  echo "# SPDX-License-Identifier: GPL-3.0-or-later"
  echo "# SPDX-FileCopyrightText: 2026 Sarah Truffle"
  echo "#"
  echo "# Standalone fit of the generated Clash $block top. No pins: this measures"
  echo "# logic utilisation and the register-to-register timing of the block itself."
  echo "# Generated by clash/tests/gen_quartus_block_project.sh."
  echo ""
  echo 'set_global_assignment -name FAMILY "Cyclone V"'
  echo "set_global_assignment -name DEVICE 5CSEBA6U23I7"
  echo "set_global_assignment -name TOP_LEVEL_ENTITY $top"
  for rtl in "$@"; do
    echo "set_global_assignment -name VERILOG_FILE $rtl"
  done
  echo "set_global_assignment -name SDC_FILE $rev.sdc"
  echo "set_global_assignment -name NUM_PARALLEL_PROCESSORS 4"
  echo "# Logic-only fit: no board pins are assigned, so make every port virtual."
  echo "set_instance_assignment -name VIRTUAL_PIN ON -to *"
} >"$dir/$rev.qsf"

# CLOCK_NS selects the constraint the block is fitted against: the shipping
# 3D island clock is 100.541946 MHz (9.946 ns); 29.838 ns is clk1x at 3:1, the
# clock a 3D pipeline that cannot close at 100.5 MHz would have to run at.
clock_ns=${CLOCK_NS:-9.946}
half_ns=$(awk -v p="$clock_ns" 'BEGIN { printf "%.3f", p / 2 }')
{
  echo "# SPDX-License-Identifier: GPL-3.0-or-later"
  echo "# SPDX-FileCopyrightText: 2026 Sarah Truffle"
  echo "#"
  echo "# Constrained at a ${clock_ns} ns period; CLOCK_NS set by the driver."
  echo ""
  echo "create_clock -name clk -period ${clock_ns} -waveform {0.000 ${half_ns}} [get_ports {CLK}]"
  echo "derive_clock_uncertainty"
} >"$dir/$rev.sdc"

echo "$dir/$rev.{qpf,qsf,sdc}"
