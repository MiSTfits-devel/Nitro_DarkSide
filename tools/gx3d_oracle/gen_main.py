"""Generate the headless raster oracle from the vendored melonDS sources."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "..", "NDS4MiSTer", "third_party", "melonDS", "src")


def grab(pattern, text):
    match = re.search(pattern, text)
    if not match:
        sys.exit("missing pattern: " + pattern)
    return match


soft_h = open(os.path.join(SRC, "GPU3D_Soft.h")).read()
soft_cpp = open(os.path.join(SRC, "GPU3D_Soft.cpp")).read()
gpu3d_h = open(os.path.join(SRC, "GPU3D.h")).read()
gpu3d_cpp = open(os.path.join(SRC, "GPU3D.cpp")).read()

alpha_lines = list(re.finditer(
    r"\(polygon->Attr >> (\d+)\) & (0x[0-9A-Fa-f]+|\d+)", soft_cpp))
alpha_shift = max(int(m.group(1)) for m in alpha_lines)
alpha_mask = max(int(m.group(2), 0) for m in alpha_lines
                 if int(m.group(1)) == alpha_shift)

height = int(grab(r"VisibleScanlines = (\d+)", soft_h).group(1))
width = int(grab(r"ScrolledLine\[(\d+)\]", soft_h).group(1))

bounds = grab(
    r"s32 ytop = (\d+), ybot = (\d+);\s*\n\s*s32 xtop = (\d+), xbot = (\d+);",
    gpu3d_cpp)
yt_init, yb_init, xt_init, xb_init = (int(v) for v in bounds.groups())

zero = 0
one = 1
two = one + one
three = two + one
four = three + one
five = four + one
nine = three * three

alpha_width = alpha_mask.bit_length()
alpha = (one << alpha_width) - one
chan_width = alpha_width + one
chan_mask = (one << chan_width) - one
c_shift_one = chan_width
c_shift_two = chan_width * two

positions = grab(r"FinalPosition\[(\d+)\]", gpu3d_h)
colors = grab(r"FinalColor\[(\d+)\]", gpu3d_h)
pos_count = int(positions.group(1)) + one
col_count = int(colors.group(1)) + one

values = {
    "zero": zero,
    "one": one,
    "two": two,
    "three": three,
    "four": four,
    "five": five,
    "nine": nine,
    "alpha": alpha,
    "alpha_shift": alpha_shift,
    "chan_mask": chan_mask,
    "c_shift_one": c_shift_one,
    "c_shift_two": c_shift_two,
    "pos_count": pos_count,
    "col_count": col_count,
    "yt_init": yt_init,
    "yb_init": yb_init,
    "xt_init": xt_init,
    "xb_init": xb_init,
    "height": height,
    "width": width,
}

template = """// SPDX-License-Identifier: GPL-3.0-or-later
// SPDX-FileCopyrightText: 2026 Sarah Truffle
//
// Generated by gen_main.py from the vendored melonDS sources. Edit the
// generator, not this file.
//
// Reads triangles from stdin, one per line:
//
//   TRI x0 y0 x1 y1 x2 y2 r g b
//
// Each triangle is rendered in its own frame by the production melonDS
// software rasteriser; one %(width)dx%(height)d RGBA word buffer is written
// per triangle.
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <memory>
#include <vector>

#include "NDS.h"
#include "GPU.h"
#include "GPU3D.h"
#include "GPU3D_Soft.h"
#include "GPU_Soft.h"

using namespace melonDS;

struct Tri
{
    s32 x[%(three)d];
    s32 y[%(three)d];
    u32 color;
    bool facing;
};

static bool readTri(Tri& tri)
{
    char kind[%(five)d];
    if (std::scanf("%%%(four)ds", kind) != %(one)d) return false;
    if (std::strcmp(kind, "TRI") != %(zero)d) return false;
    unsigned r, g, b;
    if (std::scanf("%%d %%d %%d %%d %%d %%d %%u %%u %%u",
            &tri.x[%(zero)d], &tri.y[%(zero)d], &tri.x[%(one)d], &tri.y[%(one)d],
            &tri.x[%(two)d], &tri.y[%(two)d], &r, &g, &b) != %(nine)d)
        return false;
    int face = %(one)d;
    if (std::scanf("%%d", &face) != %(one)d) face = %(one)d;
    tri.facing = face != %(zero)d;
    tri.color = (r & %(chan_mask)d) | ((g & %(chan_mask)d) << %(c_shift_one)d) |
        ((b & %(chan_mask)d) << %(c_shift_two)d);
    return true;
}

int main()
{
    auto ndsHolder = std::make_unique<NDS>();
    NDS& nds = *ndsHolder;
    auto softHolder = std::make_unique<SoftRenderer>(nds);
    SoftRenderer& soft = *softHolder;
    SoftRenderer3D* r3d = soft.Get3DRenderer();
    GPU3D& gpu3d = nds.GPU.GPU3D;

    u32 dispcnt = %(zero)d;
    if (const char* env = std::getenv("ORACLE_DISPCNT"))
        dispcnt = static_cast<u32>(std::strtoul(env, nullptr, 0));
    gpu3d.RenderDispCnt = dispcnt;
    gpu3d.RenderAlphaRef = %(zero)d;
    gpu3d.RenderClearAttr1 = %(zero)d;
    gpu3d.RenderClearAttr2 = %(zero)d;
    gpu3d.RenderXPos = %(zero)d;

    std::vector<Tri> tris;
    Tri tri;
    while (readTri(tri)) tris.push_back(tri);

    Vertex vertices[%(three)d];
    Polygon polygon;

    for (const Tri& t : tris)
    {
        Polygon& p = polygon;
        p.NumVertices = %(three)d;
        p.Attr = %(alpha)d << %(alpha_shift)d;
        p.TexParam = %(zero)d;
        p.TexPalette = %(zero)d;
        p.Degenerate = false;
        p.FacingView = t.facing;
        p.WBuffer = false;
        p.Translucent = false;
        p.IsShadowMask = false;
        p.IsShadow = false;
        p.Type = %(zero)d;
        p.SortKey = %(zero)d;

        s32 ytop = %(yt_init)d, ybot = %(yb_init)d;
        s32 xtop = %(xt_init)d, xbot = %(xb_init)d;
        u32 vtop = %(zero)d, vbot = %(zero)d;
        for (u32 v = %(zero)d; v < %(three)d; ++v)
        {
            Vertex& vert = vertices[v];
            vert.FinalPosition[%(zero)d] = t.x[v];
            vert.FinalPosition[%(one)d] = t.y[v];
            vert.FinalColor[%(zero)d] = (t.color & %(chan_mask)d);
            vert.FinalColor[%(one)d] = ((t.color >> %(c_shift_one)d) & %(chan_mask)d);
            vert.FinalColor[%(two)d] = ((t.color >> %(c_shift_two)d) & %(chan_mask)d);
            p.Vertices[v] = &vert;
            p.FinalZ[v] = %(zero)d;
            p.FinalW[v] = %(zero)d;
            if (t.y[v] < ytop) { ytop = t.y[v]; xtop = t.x[v]; vtop = v; }
            if (t.y[v] > ybot || (t.y[v] == ybot && t.x[v] > xbot))
            { ybot = t.y[v]; xbot = t.x[v]; vbot = v; }
        }
        p.YTop = ytop;
        p.YBottom = ybot;
        p.VTop = vtop;
        p.VBottom = vbot;
        p.XTop = xtop;
        p.XBottom = xbot;

        Polygon* ptr = &p;
        r3d->RenderFrame(&ptr, %(one)d);

        for (u32 y = %(zero)d; y < %(height)d; ++y)
            std::fwrite(r3d->GetLine(static_cast<int>(y)),
                sizeof(u32), %(width)d, stdout);
    }
    return %(zero)d;
}
"""

out = os.path.join(HERE, "main.cpp")
with open(out, "w") as handle:
    handle.write(template % values)
print("wrote", out)
